const assert = require('node:assert/strict');
const {generate} = require('../app/static/compatibility.js');
const values = {url:'https://homepage.example.com:8443',secret:'x'.repeat(40),password:'pa$WORD${OTHER}"\\end'};
const hidden = generate('password',values);
const literal = generate('password',values,true);
assert.equal(literal.errors.length,0);
assert(!hidden.yaml.includes(values.password));
assert(literal.yaml.includes('pa$$WORD$${OTHER}'));
assert(literal.yaml.includes('homepage.example.com:8443'));
assert(generate('password',{...values,url:'https://user:pass@example.com'}).errors.length);
assert(generate('password',{...values,secret:'short'}).errors.length);
const oidc=generate('oidc',{...values,issuer:'https://id.example.com/realms/homepage',clientId:'homepage',clientSecret:'client$SECRET',scope:'openid profile',autoLogin:true},true);
assert(oidc.yaml.includes('HOMEPAGE_OIDC_AUTO_LOGIN'));
assert(oidc.endpoint.includes('/api/auth/callback/homepage-oidc'));
assert(!oidc.yaml.includes('HOMEPAGE_AUTH_PASSWORD'));
assert(generate('oidc',{...values,version:'2.2.0',autoLogin:true}).errors.length);
const mcp=generate('mcp',{url:values.url});
assert(mcp.yaml.includes('${HOMEPAGE_MCP_TOKEN}'));
assert(!mcp.yaml.includes('ALLOW_WRITE'));
assert(generate('mcp',{url:values.url,token:'short'}).errors.length);
assert(generate('mcp',{url:values.url,write:true}).yaml.includes('ALLOW_WRITE'));
console.log(JSON.stringify({checks:15,passwordYaml:literal.yaml,password:values.password}));
